package com.ok.refund.domain;

/**
 * 승인 처리 중 멈춘 단계. 흐름 순서대로 둔다.
 * 1차 구현에는 자동 재시도가 없어, 운영자가 이 값을 보고 어디부터 다시 할지 판단한다.
 */
public enum RefundFailedStep {

    /**
     * 흐름 5번 배송 잠금. 409(거절)는 승인 불가로 끝나 여기 오지 않고, 그 밖의 실패(응답 없음, 5xx, 409가 아닌 4xx)가 여기 기록된다.
     * 응답이 없으면 잠금이 걸렸는지 모르므로 승인 불가로 끝낼 수 없다. 설계 11장에서 미룬 것을 최소로 당겨 쓴 값이다
     */
    SHIPMENT_RESERVE,
    /** 흐름 6번 지갑 환불 */
    WALLET,
    /** 흐름 7번 주문 취소 수량 반영 */
    ORDER,
    /** 흐름 8번 상품 재고 되돌리기 */
    PRODUCT,
    /** 흐름 9번 배송 잠금 해제 */
    SHIPMENT_CONFIRM
}
