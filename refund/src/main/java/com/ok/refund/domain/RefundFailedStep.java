package com.ok.refund.domain;

/**
 * 승인 뒤 처리 중에 멈춘 단계. 처리 순서대로 둔다.
 * 1단계에는 자동으로 다시 처리하는 방법이 없어, 운영자가 이 값을 보고 어디부터 다시 할지 판단한다.
 * 값은 #413·#414가 실제 호출을 붙이며 쓴다(이슈 본문에 정한 이름).
 */
public enum RefundFailedStep {

    /** 주문 취소 수량 반영 (#413). 주문을 먼저 반영해 거절당하면 돈이 움직이기 전에 끝낸다 */
    ORDER,
    /** 지갑 예치금 반환 (#413) */
    WALLET,
    /** 상품 재고 되돌리기 (#414) */
    PRODUCT
}
