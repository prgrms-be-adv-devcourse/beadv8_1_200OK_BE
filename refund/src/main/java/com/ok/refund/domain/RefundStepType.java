package com.ok.refund.domain;

/**
 * 승인 뒤 처리 단계의 종류. 처리 순서대로 둔다.
 * 단계 진행 표(refund_step)의 단계 구분에 쓴다. 환불이 멈춘 곳도 이 표의 단계 줄로 남는다(#574).
 * 1단계에는 자동으로 다시 처리하는 방법이 없어, 운영자가 이 값을 보고 어디부터 다시 할지 판단한다.
 * DB 컬럼에는 enum 이름이 그대로 저장되므로 값 이름을 바꾸지 않는다.
 */
public enum RefundStepType {

    /** 주문 취소 수량 반영 (#513). 주문을 먼저 반영해 거절당하면 돈이 움직이기 전에 끝낸다 */
    ORDER,
    /** 지갑 예치금 반환 (#512) */
    WALLET,
    /** 상품 재고 되돌리기 (#414) */
    PRODUCT,
    /**
     * 지갑 돈 다시 가져오기(회수, #546). 재고가 다시 해도 같은 이유로 거절되면(PRODUCT_RELEASE_REFUSED) 이미 돌려준 돈을 다시 가져온다.
     * 앞 단계를 되돌리는 단계라 정상 단계 뒤에 두고(되돌리는 순서는 지갑 먼저라 주문 되돌리기 앞), 이 줄이 생긴 환불은 앞으로 가지 않는다(RefundSagaPlan.fromSteps)
     */
    WALLET_REVERT,
    /**
     * 주문 취소 기록 되돌리기(#622). 지갑이 반환에 실패했거나 회수가 성공한 뒤, 주문에 남긴 취소 기록(수량·뺀 배송비)을 되돌려 달라고 한다.
     * 되돌리는 순서가 지갑 먼저, 주문 다음이라(PR #537) 회수 뒤에 둔다. 이 줄이 생긴 환불은 이 줄만 보고 끝을 기다린다(RefundSagaPlan.fromSteps)
     */
    ORDER_REVERT
}
