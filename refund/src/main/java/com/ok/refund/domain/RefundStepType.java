package com.ok.refund.domain;

/**
 * 승인 뒤 처리 단계의 종류. 처리 순서대로 둔다.
 * 단계 진행 표(refund_step)의 단계 구분에 쓰고, 환불이 멈춘 곳(failed_step)을 기록할 때도 쓴다.
 * 1단계에는 자동으로 다시 처리하는 방법이 없어, 운영자가 이 값을 보고 어디부터 다시 할지 판단한다.
 * DB 컬럼에는 enum 이름이 그대로 저장되므로 값 이름을 바꾸지 않는다.
 */
public enum RefundStepType {

    /** 주문 취소 수량 반영 (#513). 주문을 먼저 반영해 거절당하면 돈이 움직이기 전에 끝낸다 */
    ORDER,
    /** 지갑 예치금 반환 (#512) */
    WALLET,
    /** 상품 재고 되돌리기 (#414) */
    PRODUCT
}
