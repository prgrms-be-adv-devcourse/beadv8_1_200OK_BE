package com.ok.member.member.domain;

/**
 * 회원 유형. "이 계정은 어떤 종류인가"를 나타낸다.
 *
 * <p>"무엇을 할 수 있는가"(구매·판매·운영 권한)는 이 값이 아니라 토큰을 발급할 때 계산한다.
 * 판매자는 회원 유형이 아니라 판매자 신청·승인 상태로 정해지므로 여기에 두지 않는다.
 * 토큰 권한과 헷갈리지 않도록 이름에 "Role"을 쓰지 않는다.
 */
public enum MemberType {

    /** 일반 회원. 구매할 수 있고, 판매자 승인을 받으면 판매도 할 수 있다. */
    USER,

    /** 관리자. 운영 전용 계정이라 구매·판매를 하지 않는다. */
    ADMIN

}
