package com.ok.payout.domain;

// 관리자 조정이 금액 검사에 들어가는지 (#791). 정산후보 조회(관리자, 주문 ID)에서 조정 줄마다 보여 줌
// 판정은 금액 검사와 같은 확인한 조정 조건(#291 결정 4번)과 해결 대기 조건(#723)을 그대로 씀
public enum PayoutAdjustmentCheckStatus {

    // 확인됨: 금액 불일치·수수료 불일치 실패 뒤, 해결 전에 넣고 해결한 조정. 금액 검사에 들어감
    CONFIRMED,

    // 해결 대기: 해결 안 된 금액 불일치·수수료 불일치 실패 뒤에 넣은 조정. 해결하면 확인됨이 됨
    //   막힌 주문 상태의 PENDING(예비)과 헷갈리지 않게 이름을 다르게 둠
    AWAITING_RESOLUTION,

    // 검사 밖: 위 둘이 아닌 조정(실패 전에 미리 넣음, 해결 뒤에 넣음, 막힘과 상관없음). 금액 검사 없이 지급에만 들어감
    //   조건을 따로 두지 않고 "나머지"로 정함: 따로 쓰면 두 판정과 경계(같은 시각, 사유)가 어긋날 수 있음
    UNCHECKED
}
