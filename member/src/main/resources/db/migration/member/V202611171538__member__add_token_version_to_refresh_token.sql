-- 기존 행은 회원 버전의 기본값과 같은 0으로 두어 배포만으로 세션이 끊기지 않게 한다
ALTER TABLE refresh_token
    ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0 COMMENT '세션을 연 로그인 당시의 회원 토큰 버전';
